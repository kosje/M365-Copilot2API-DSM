func TestChatImagesReachExternalClientProtocols(t *testing.T) {
	t.Setenv("M365_DATA_DIR", t.TempDir())
	var data bytes.Buffer
	if err := png.Encode(&data, image.NewRGBA(image.Rect(0, 0, 2, 2))); err != nil {
		t.Fatal(err)
	}
	source := "data:image/png;base64," + base64.StdEncoding.EncodeToString(data.Bytes())
	s := &Server{}
	r := httptest.NewRequest("POST", "https://nas.example/v1/chat/completions", nil)
	urls, err := s.hostChatImages(r.Context(), r, []string{source, source}, auth.AccountToken{})
	if err != nil || len(urls) != 1 {
		t.Fatalf("deduped URLs=%v err=%v", urls, err)
	}
	rr := httptest.NewRecorder()
	s.generatedImageFile(rr, httptest.NewRequest("GET", urls[0], nil))
	if rr.Code != http.StatusOK || !bytes.Equal(rr.Body.Bytes(), data.Bytes()) {
		t.Fatal("anonymous image download did not match generated bytes")
	}
	md := "![image](" + urls[0] + ")"
	for _, stream := range []bool{false, true} {
		out := httptest.NewRecorder()
		s.writeChatCompletionText(out, r, "gpt-image-2", md, stream, true, 1)
		if !strings.Contains(out.Body.String(), urls[0]) {
			t.Fatal("OpenAI output lost image URL")
		}
	}
	out := httptest.NewRecorder()
	s.writeChatCompletionText(out, r, "gpt-image-2", md, false, true, 1)
	var payload map[string]any
	if err := json.Unmarshal(out.Body.Bytes(), &payload); err != nil {
		t.Fatal(err)
	}
	for _, stream := range []bool{false, true} {
		converted := httptest.NewRecorder()
		writeAnthropicResult(converted, "gpt-image-2", stream, payload)
		if !strings.Contains(converted.Body.String(), urls[0]) {
			t.Fatal("Anthropic output lost image URL")
		}
	}
}

